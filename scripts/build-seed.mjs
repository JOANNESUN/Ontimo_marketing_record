// Builds migrations/0002_seed.sql from scripts/locations.tsv.
// Run: node scripts/build-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const rows = readFileSync(join(here, "locations.tsv"), "utf8").trim().split("\n").slice(1).map(l => l.split("\t"));
const q = s => "'" + String(s).replace(/'/g, "''") + "'";
const now = Date.UTC(2026, 10, 4);

const out = ["-- Generated by scripts/build-seed.mjs. Edit scripts/locations.tsv, not this file."];
out.push(`INSERT OR IGNORE INTO docs (collection, id, data, deleted, created_at, updated_at) VALUES ('settings', 'main', ${q(JSON.stringify({ startDate: "", hourlyRate: 1000 }))}, 0, ${now}, ${now});`);
for (const [id, name, district, cat, group, address, phone, note, chain, week] of rows) {
  const doc = { name, district, cat, group, address, phone, note, chain: chain === "1", status: "new", star: false,
    week: week ? Number(week) : null, memo: "" };
  out.push(`INSERT OR IGNORE INTO docs (collection, id, data, deleted, created_at, updated_at) VALUES ('locations', ${q(id)}, ${q(JSON.stringify(doc))}, 0, ${now}, ${now});`);
}
writeFileSync(join(here, "..", "migrations", "0002_seed.sql"), out.join("\n") + "\n");
console.log(`Wrote ${rows.length} locations.`);
